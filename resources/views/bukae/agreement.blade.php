    <h3>개인정보 처리방침</h3>
</div>
<div>
    오늘의 부캐(이하 "이 앱")는 정보통신망 이용촉진 및 정보보호 등에 관한 법률, 개인정보보호법 등 관련 법령상의 개인정보보호 규정을 준수하며, 이용자 권익 보호에 최선을 다하고 있습니다.<br />
    <br />
    1. 수집하는 정보 및 이용 목적<br />
    이 앱은 회원가입·로그인이 없으며 이름·전화번호·이메일 등 개인을 식별하는 정보를 요구하지 않습니다.<br />
    - <strong>익명 사용 통계</strong>: 서비스 품질 개선을 위해 Google Firebase Analytics를 통해 앱 실행·화면 이동 등 이벤트, 기기 종류·OS 버전 등 기술 정보를 수집합니다. 이 정보는 개인을 식별하지 않으며 앱 개선·오류 파악 목적으로만 사용됩니다.<br />
    - <strong>기기에 저장되는 데이터</strong>: 이용자가 만든 부캐(도감)는 기본적으로 이용자 기기 안에 저장됩니다.<br />
    - <strong>담벼락(소셜) 이용 시 서버로 전송·공개되는 데이터</strong>: 이용자가 부캐를 <strong>'담벼락에 올리기'로 직접 선택</strong>하면, 해당 부캐의 구성 정보(얼굴 부품 조합값과 앱이 기본 제공하는 아키타입·태그라인 문구 — 이용자 자유 입력 텍스트/사진은 없습니다)와 <strong>익명 기기 식별자(device_id)</strong>가 당사 서버로 전송되어 다른 이용자에게 공개됩니다. 다른 부캐에 대한 <strong>반응(고정 이모지)·신고</strong> 역시 익명 기기 식별자와 함께 서버로 전송됩니다. 이 식별자는 계정 없이 반응·신고 중복 방지 및 게시물 귀속에만 사용되며 개인을 식별하지 않습니다.<br />
    - <strong>알림</strong>(선택 기능)은 기기 내 로컬 알림으로, 별도의 정보를 수집하지 않습니다.<br />
    - 이 앱은 <strong>광고를 포함하지 않습니다.</strong><br />
    <br />
    2. 이용자 콘텐츠 및 모더레이션<br />
    담벼락에 게시된 부캐는 다른 이용자에게 공개됩니다. 부적절한 게시물에 대비해 <strong>신고(🚩)</strong>와 <strong>숨기기(👁)</strong> 기능을 제공하며, 신고가 일정 횟수 이상 누적된 게시물은 자동으로 비공개 처리됩니다. 이용자는 자신이 올린 게시물의 삭제를 아래 문의처로 요청할 수 있습니다(기준: 익명 기기 식별자).<br />
    <br />
    3. 제3자 제공 및 처리위탁<br />
    이 앱은 수집한 정보를 판매하거나 광고 목적으로 제3자에게 제공하지 않습니다. 서비스 운영·분석을 위해 아래를 이용하며, 해당 정보의 취급에는 각 사의 개인정보 정책이 적용됩니다.<br />
    - 담벼락 게시물·반응·신고 데이터는 개발자(idiotlabs)가 운영하는 서버(Amazon Web Services, 서울 리전)에 저장됩니다.<br />
    - Google Play Services : https://www.google.com/policies/privacy/<br />
    - Google/Firebase Analytics : https://firebase.google.com/policies/analytics<br />
    <br />
    4. 보관 및 파기<br />
    익명 사용 통계는 분석 목적 달성에 필요한 기간 동안 보관 후 파기됩니다. 기기 내 저장 데이터는 앱을 삭제하면 함께 삭제됩니다. 담벼락에 게시한 데이터는 서버에 보관되며, 이용자의 삭제 요청 또는 서비스 종료 시 파기됩니다(앱 삭제만으로는 서버 공개분이 자동 삭제되지 않으므로 삭제를 원하면 문의처로 요청해 주세요).<br />
    <br />
