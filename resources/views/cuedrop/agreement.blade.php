    <h3>1. 개요</h3>
    CueDrop(이하 "이 앱")은 사용자가 받은 알림 메시지에서 만료일을 자동으로 추적하는 모바일 앱입니다. 정보통신망 이용촉진 및 정보보호 등에 관한 법률, 개인정보보호법 등 관련 법령을 준수합니다.

    <h3>2. 수집하는 정보 및 보관 위치</h3>
    이 앱은 다음 정보를 수집·처리하나, <strong>모든 정보는 사용자의 기기 내부에만 저장되며 외부 서버로 전송되지 않습니다</strong>:<br />
    - 사용자가 직접 입력하거나 클립보드/공유로 전달한 알림 텍스트 (도서명·도서관명·구독명·만료일 등)<br />
    - 만료 알림 스케줄 (D-3, D-1, 당일 오전 9시)<br />
    회원 가입 및 로그인을 요구하지 않으며, 이름·이메일·전화번호·결제 정보 등 개인 식별 정보를 수집하지 않습니다.

    <h3>3. 권한</h3>
    이 앱은 다음 권한을 사용합니다:<br />
    - 알림 권한 (POST_NOTIFICATIONS) : 만료일 알림 표시<br />
    - 정확한 알람 권한 (SCHEDULE_EXACT_ALARM / USE_EXACT_ALARM) : 지정된 시각에 정확히 알림 발송<br />
    - 부팅 완료 수신 (RECEIVE_BOOT_COMPLETED) : 기기 재부팅 후 알림 복구<br />
    - 진동 (VIBRATE) : 알림 진동<br />
    - 클립보드 읽기 : 사용자가 복사한 알림 텍스트를 분석해 만료일 자동 추출<br />
    - 공유 인텐트(SEND text/plain) : 다른 앱에서 공유한 텍스트를 받아 만료일 자동 추출

    <h3>4. 외부 서비스</h3>
    이 앱은 광고를 표시할 수 있으며 함께 제공되는 광고플랫폼에서 광고 식별자 등을 수집할 수 있습니다. 이에 대한 절차 및 책임은 각 제공처에 있습니다.<br />
    - Google Play Services : https://www.google.com/policies/privacy/<br />
    - AdMob : https://support.google.com/admob/answer/6128543?hl=ko<br />
    이 앱 자체는 외부 분석 도구(Firebase Analytics 등)를 사용하지 않습니다.

    <h3>5. 데이터 삭제</h3>
    저장된 모든 알림 데이터는 사용자가 앱 내에서 직접 삭제하거나, 앱을 제거(언인스톨)하면 기기에서 함께 삭제됩니다. 별도 서버 데이터가 없어 추가 삭제 요청이 필요하지 않습니다.

