    <h3>개인정보 처리방침</h3>
</div>
<div>
    한알(이하 "이 앱")은 정보통신망 이용촉진 및 정보보호 등에 관한 법률, 개인정보보호법 등 관련 법령상의 개인정보보호 규정을 준수하며, 이용자 권익 보호에 최선을 다하고 있습니다.<br />
    <br />
    1. 수집하는 정보 및 이용 목적<br />
    이 앱은 회원가입·로그인이 없으며 이름·전화번호·이메일 등 개인을 식별하는 정보를 요구하지 않습니다.<br />
    - <strong>기기에 저장되는 데이터</strong>: 글자 크기 등 앱 설정과 내가 누른 반응 기록은 기본적으로 이용자 기기 안에 저장됩니다.<br />
    - <strong>반응 집계 시 서버로 전송되는 데이터</strong>: 이용자가 오늘의 말씀에 <strong>이모지 반응(은혜됨·감사함·찔림·평안함·기쁨)</strong>을 누르면, 어떤 말씀에 어떤 반응을 눌렀는지와 <strong>익명 기기 식별자(device_id)</strong>가 당사 서버로 전송됩니다. 이는 "다른 사람들도 은혜받았다"는 공동체감을 위한 <strong>익명 집계 숫자</strong>를 표시하고 중복 집계를 방지하기 위한 것으로, 이용자가 자유롭게 입력한 글이나 사진은 수집·전송하지 않으며, 이 식별자는 개인을 식별하지 않습니다.<br />
    - <strong>오늘의 말씀</strong>은 당사 서버에서 생성되어 앱으로 전달됩니다. 앱이 말씀을 불러올 때 개인을 식별하는 정보는 전송되지 않습니다.<br />
    - <strong>익명 사용 통계</strong>: 서비스 품질 개선을 위해 Google Firebase Analytics를 통해 앱 실행, 오늘의 말씀 조회·반응·말씀카드 공유/저장 등 앱 내 이벤트와 기기 종류·OS 버전 등 기술 정보를 수집합니다. 이 정보는 개인을 식별하지 않으며 앱 개선·오류 파악 목적으로만 사용됩니다.<br />
    - 이 앱은 <strong>푸시 알림을 사용하지 않습니다.</strong><br />
    - 이 앱은 <strong>광고를 포함하지 않습니다.</strong><br />
    <br />
    2. 제3자 제공 및 처리위탁<br />
    이 앱은 수집한 정보를 판매하거나 광고 목적으로 제3자에게 제공하지 않습니다. 서비스 운영·분석을 위해 아래를 이용하며, 해당 정보의 취급에는 각 사의 개인정보 정책이 적용됩니다.<br />
    - 반응 집계 데이터는 개발자(idiotlabs)가 운영하는 서버(Amazon Web Services, 서울 리전)에 저장됩니다.<br />
    - 오늘의 말씀 생성에는 Google Gemini API가 이용되며, 생성 과정에 이용자의 개인정보는 전달되지 않습니다.<br />
    - Google/Firebase Analytics : https://firebase.google.com/policies/analytics<br />
    - Google Play Services : https://www.google.com/policies/privacy/<br />
    <br />
    3. 보관 및 파기<br />
    익명 사용 통계는 분석 목적 달성에 필요한 기간 동안 보관 후 파기됩니다. 기기 내 저장 데이터는 앱을 삭제하면 함께 삭제됩니다. 서버에 저장된 익명 반응 집계 데이터의 삭제를 원하시면 아래 문의처로 요청해 주세요(기준: 익명 기기 식별자).<br />
    <br />
    4. 아동의 개인정보<br />
    이 앱은 만 13세 미만 아동을 주 대상으로 하지 않으며, 아동의 개인정보를 고의로 수집하지 않습니다.<br />
    <br />
    5. 저작권 고지<br />
    이 앱이 인용하는 성경 본문은 저작권 보호기간이 만료되어 공유마당(퍼블릭 도메인)이 된 「개역한글판」을 사용합니다. 묵상 글은 인공지능(AI)이 작성한 것으로, 특정 교단·교파의 공식 입장이 아닙니다.<br />
